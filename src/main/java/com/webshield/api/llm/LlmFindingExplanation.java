package com.webshield.api.llm;

import java.io.Serializable;
import java.time.LocalDateTime;

/**
 * Validated, structured AI-assisted finding explanation.
 * Clearly marked as advisory and separated from deterministic scanner evidence.
 */
public record LlmFindingExplanation(
        Long findingId,
        String findingTitle,
        String summary,
        String potentialImpact,
        String exploitationScenario,
        String remediationGuide,
        String disclaimer,
        boolean isAiAssisted,
        String providerName,
        LocalDateTime generatedAt
) implements Serializable {

    public static final String STANDARD_DISCLAIMER =
            "AI-Assisted Security Advisory: This explanation was generated by an AI model for contextual guidance. " +
            "It does not constitute independently verified proof, nor does it override the deterministic findings, " +
            "severity, or evidence recorded by WebShield.";

    public LlmFindingExplanation {
        summary = (summary != null && !summary.isBlank()) ? summary : "No AI summary available.";
        potentialImpact = (potentialImpact != null && !potentialImpact.isBlank()) ? potentialImpact : "Potential impact assessment unavailable.";
        exploitationScenario = (exploitationScenario != null && !exploitationScenario.isBlank()) ? exploitationScenario : "Exploitation scenario unavailable.";
        remediationGuide = (remediationGuide != null && !remediationGuide.isBlank()) ? remediationGuide : "Consult official OWASP guidance for remediation.";
        disclaimer = (disclaimer != null && !disclaimer.isBlank()) ? disclaimer : STANDARD_DISCLAIMER;
        generatedAt = generatedAt != null ? generatedAt : LocalDateTime.now();
    }

    public static LlmFindingExplanation of(Long findingId, String findingTitle, String summary, String potentialImpact,
                                           String exploitationScenario, String remediationGuide, String provider) {
        return new LlmFindingExplanation(
                findingId,
                findingTitle,
                summary,
                potentialImpact,
                exploitationScenario,
                remediationGuide,
                STANDARD_DISCLAIMER,
                true,
                provider != null ? provider : "AI-Assistant",
                LocalDateTime.now()
        );
    }
}

