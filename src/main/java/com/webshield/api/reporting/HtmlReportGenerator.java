    private void appendDetailedFindings(StringBuilder sb, ApiReportData data, ApiReportConfiguration config) {
        sb.append("<section class=\"report-section\">\n");
        sb.append("  <h2>5. Detailed Findings</h2>\n");

        List<ApiFindingDto> findings = data.findings();
        if (findings.isEmpty()) {
            sb.append("  <div class=\"empty-findings-box\">No security findings were identified for this scan run.</div>\n");
            sb.append("</section>\n");
            return;
        }

        int index = 1;
        for (ApiFindingDto f : findings) {
            String sevClass = "badge-neutral";
            if ("CRITICAL".equalsIgnoreCase(f.severity())) sevClass = "badge-crit";
            else if ("HIGH".equalsIgnoreCase(f.severity())) sevClass = "badge-high";
            else if ("MEDIUM".equalsIgnoreCase(f.severity())) sevClass = "badge-med";
            else if ("LOW".equalsIgnoreCase(f.severity())) sevClass = "badge-low";
            else if ("INFO".equalsIgnoreCase(f.severity())) sevClass = "badge-info";

            sb.append("  <div class=\"finding-card\">\n");
            sb.append("    <div class=\"finding-header\">\n");
            sb.append("      <span class=\"finding-num\">#").append(index++).append("</span>\n");
            sb.append("      <span class=\"badge ").append(sevClass).append("\">").append(escapeHtml(f.severity())).append("</span>\n");
            sb.append("      <span class=\"badge badge-neutral\">Confidence: ").append(escapeHtml(f.confidence())).append("</span>\n");
            sb.append("      <h3 class=\"finding-title\">").append(escapeHtml(f.title())).append("</h3>\n");
            sb.append("    </div>\n");

            sb.append("    <div class=\"finding-body\">\n");
            sb.append("      <div class=\"finding-meta-row\">\n");
            sb.append("        <div><strong>Affected Endpoint:</strong> <span class=\"mono\">")
                    .append(f.httpMethod() != null ? f.httpMethod() + " " : "")
                    .append(escapeHtml(f.endpointPath())).append("</span></div>\n");
            if (f.parameterOrField() != null && !f.parameterOrField().isBlank()) {
                sb.append("        <div><strong>Vulnerable Parameter:</strong> <span class=\"mono\">")
                        .append(escapeHtml(f.parameterOrField())).append("</span></div>\n");
            }
            sb.append("        <div><strong>OWASP Category:</strong> ").append(escapeHtml(f.owaspCategory() != null ? f.owaspCategory() : "—")).append("</div>\n");
            sb.append("        <div><strong>CWE ID:</strong> <span class=\"mono\">").append(escapeHtml(f.cweId() != null ? f.cweId() : "—")).append("</span></div>\n");
            sb.append("      </div>\n");

            sb.append("      <div class=\"finding-field\">\n");
            sb.append("        <h4>Description</h4>\n");
            sb.append("        <p>").append(escapeHtml(f.description())).append("</p>\n");
            sb.append("      </div>\n");

            if (f.evidence() != null && !f.evidence().isBlank()) {
                sb.append("      <div class=\"finding-field\">\n");
                sb.append("        <h4>Observed Evidence</h4>\n");
                sb.append("        <pre class=\"code-block\">").append(escapeHtml(RedactionUtils.redactSensitiveData(f.evidence()))).append("</pre>\n");
                sb.append("      </div>\n");
            }

            sb.append("      <div class=\"finding-field\">\n");
            sb.append("        <h4>Remediation Guidance</h4>\n");
            sb.append("        <p>").append(escapeHtml(f.remediation() != null && !f.remediation().isBlank()
                    ? f.remediation() : "Consult OWASP guidelines to harden this endpoint against unauthorized actions.")).append("</p>\n");
            sb.append("      </div>\n");

            // AI-Assisted Section (if requested and available)
            if (config.includeAiExplanations() && data.aiExplanations().containsKey(f.id())) {
                LlmFindingExplanation ai = data.aiExplanations().get(f.id());
                appendAiExplanationCard(sb, ai);
            }

            sb.append("    </div>\n"); // finding-body
            sb.append("  </div>\n"); // finding-card
        }
        sb.append("</section>\n");
    }

