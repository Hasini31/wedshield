        sb.append("  <h2>4. Vulnerability Overview</h2>\n");

        // Severity Bar Chart
        sb.append("  <h3>Severity Distribution</h3>\n");
        int total = Math.max(1, data.findings().size());
        sb.append("  <div class=\"chart-bar-container\">\n");
        if (data.getCriticalCount() > 0) sb.append("    <div class=\"bar bar-crit\" style=\"width: ").append((data.getCriticalCount() * 100) / total).append("%;\" title=\"Critical: ").append(data.getCriticalCount()).append("\">").append(data.getCriticalCount()).append(" Crit</div>\n");
        if (data.getHighCount() > 0) sb.append("    <div class=\"bar bar-high\" style=\"width: ").append((data.getHighCount() * 100) / total).append("%;\" title=\"High: ").append(data.getHighCount()).append("\">").append(data.getHighCount()).append(" High</div>\n");
        if (data.getMediumCount() > 0) sb.append("    <div class=\"bar bar-med\" style=\"width: ").append((data.getMediumCount() * 100) / total).append("%;\" title=\"Medium: ").append(data.getMediumCount()).append("\">").append(data.getMediumCount()).append(" Med</div>\n");
        if (data.getLowCount() > 0) sb.append("    <div class=\"bar bar-low\" style=\"width: ").append((data.getLowCount() * 100) / total).append("%;\" title=\"Low: ").append(data.getLowCount()).append("\">").append(data.getLowCount()).append(" Low</div>\n");
        if (data.getInfoCount() > 0) sb.append("    <div class=\"bar bar-info\" style=\"width: ").append((data.getInfoCount() * 100) / total).append("%;\" title=\"Info: ").append(data.getInfoCount()).append("\">").append(data.getInfoCount()).append(" Info</div>\n");
        sb.append("  </div>\n");

        // OWASP Table
        sb.append("  <h3>OWASP API Security Top 10 Categorization</h3>\n");
        sb.append("  <table class=\"data-table\">\n");
        sb.append("    <thead><tr><th>OWASP Category</th><th>Findings Count</th><th>Risk Level</th></tr></thead>\n");
