    private void appendExecutiveSummary(StringBuilder sb, ApiReportData data) {
        sb.append("<section class=\"report-section\">\n");
        sb.append("  <h2>1. Executive Summary</h2>\n");
        sb.append("  <p class=\"section-desc\">An automated dynamic API security assessment was conducted against the target application to discover schema non-compliances, injection vectors, authorization weaknesses, and sensitive data exposures.</p>\n");

        sb.append("  <div class=\"metrics-deck\">\n");
        appendMetricCard(sb, "Critical", String.valueOf(data.getCriticalCount()), "crit-card");
        appendMetricCard(sb, "High", String.valueOf(data.getHighCount()), "high-card");
        appendMetricCard(sb, "Medium", String.valueOf(data.getMediumCount()), "med-card");
        appendMetricCard(sb, "Low", String.valueOf(data.getLowCount()), "low-card");
        appendMetricCard(sb, "Info", String.valueOf(data.getInfoCount()), "info-card");
        appendMetricCard(sb, "Total Findings", String.valueOf(data.findings().size()), "total-card");
        sb.append("  </div>\n");

        ApiScanDto scan = data.scan();
        sb.append("  <div class=\"summary-callout\">\n");
        sb.append("    <strong>Assessment Observations:</strong> During this scan, ");
        if (scan != null) {
            sb.append("a total of <strong>").append(scan.totalExecutedRequests()).append(" HTTP requests</strong> were dispatched across ");
            sb.append("<strong>").append(scan.totalEndpoints()).append(" API endpoints</strong> over a duration of ");
            sb.append("<strong>").append(scan.durationMs() > 0 ? (scan.durationMs() / 1000.0) + "s" : "less than a second").append("</strong>. ");
        }
        if (data.getCriticalCount() > 0 || data.getHighCount() > 0) {
            sb.append("<span class=\"text-danger\">Critical and/or High severity vulnerabilities were identified that pose severe risks of unauthorized data access, privilege escalation, or systemic compromise. Immediate remediation is strongly recommended.</span>");
        } else if (data.findings().isEmpty()) {
            sb.append("<span class=\"text-success\">No active vulnerabilities were detected under the configured objective rules. Continued regression testing and manual review are recommended.</span>");
        } else {
            sb.append("Moderate and informational observations were cataloged regarding error disclosure, missing defense-in-depth headers, or schema strictness.");
        }
        sb.append("  </div>\n");
        sb.append("</section>\n");
    }

